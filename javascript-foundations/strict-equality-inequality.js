// Strict equality (===)
console.log(5 === 5);         // true  (Number === Number)
console.log(5 === "5");       // false (Number !== String)
console.log(true === 1);      // false (Boolean !== Number)

// Strict inequality (!==)
console.log(10 !== 20);       // true  (different values)
console.log(10 !== "10");     // true  (different types)
console.log(10 !== 10);       // false (same type and value)